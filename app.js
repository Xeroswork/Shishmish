const DEFAULT_LANG = 'bg';
let currentLang = DEFAULT_LANG;

function applyLang(lang) {
  const dict = I18N[lang] || I18N[DEFAULT_LANG];
  currentLang = I18N[lang] ? lang : DEFAULT_LANG;

  document.documentElement.lang = currentLang;
  if (dict.doc_title) document.title = dict.doc_title;

  // Текстово съдържание (нашите низове са доверени -> innerHTML заради <br/>)
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const val = dict[el.dataset.i18n];
    if (val != null) el.innerHTML = val;
  });

  // aria-label на бутоните за количество
  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const val = dict[el.dataset.i18nAriaLabel];
    if (val != null) el.setAttribute('aria-label', val);
  });

  // Имена на артикулите за кошницата/съобщението
  document.querySelectorAll('.qty[data-name-key]').forEach(q => {
    const val = dict[q.dataset.nameKey];
    if (val != null) q.dataset.name = val;
  });

  try { localStorage.setItem('lang', currentLang); } catch (e) { /* private mode */ }

  // Пресмятане отново -> обновява текста на съобщението за поръчка
  updateTotal();
}

// ===== CART LOGIC =====

// Номер, на който пристигат поръчките (Viber / WhatsApp)
const PHONE = '359888245737';

// Текущият текст на поръчката (за копиране при клик на Viber)
let currentOrderText = '';

// Формат цени: 16.00 -> "16", 14.50 -> "14.5", 6.5 -> "6.5"
function formatPrice(value) {
  return value
    .toFixed(2)
    .replace(/\.?0+$/, '');
}

function changeQty(btn, delta) {
  const qtyEl = btn.closest('.qty');
  const valEl = qtyEl.querySelector('.qty__val');
  let val = parseInt(valEl.textContent, 10) + delta;
  if (val < 0) val = 0;
  valEl.textContent = val;
  updateTotal();
}

function updateTotal() {
  const t = I18N[currentLang] || I18N[DEFAULT_LANG];
  let total = 0;
  const items = [];

  document.querySelectorAll('.qty').forEach(qtyEl => {
    const price = parseFloat(qtyEl.dataset.price);
    const name  = qtyEl.dataset.name;
    const qty   = parseInt(qtyEl.querySelector('.qty__val').textContent, 10);
    if (qty > 0) {
      total += price * qty;
      items.push(`• ${name} × ${qty} — ${formatPrice(price * qty)} €`);
    }
  });

  // Знакът € е в отделен span, за да е по-малък и повдигнат (premium стил)
  document.getElementById('total').innerHTML =
    formatPrice(total) + ' <span class="price-cur">€</span>';

  const orderBtns = document.getElementById('order-btns');
  if (total > 0) {
    orderBtns.style.display = 'flex';
    // Красиво форматирана заявка за поръчка
    const message =
      t.order_header + '\n' +
      '━━━━━━━━━━━━━━\n' +
      items.join('\n') + '\n' +
      '━━━━━━━━━━━━━━\n' +
      t.order_total + ' ' + formatPrice(total) + ' €';
    currentOrderText = message;
    const msg = encodeURIComponent(message);
    document.getElementById('wa-link').href = `https://wa.me/${PHONE}?text=${msg}`;
    // Viber не поддържа предварително попълнен текст към конкретен номер,
    // затова отваряме чат с номера, а текстът се копира в клипборда при клик.
    document.getElementById('viber-link').href = `viber://chat?number=${PHONE}`;
  } else {
    currentOrderText = '';
    orderBtns.style.display = 'none';
  }
}

// ===== VIBER: копиране на поръчката в клипборда при клик =====
function copyToClipboard(text) {
  if (navigator.clipboard && navigator.clipboard.writeText) {
    return navigator.clipboard.writeText(text).catch(() => fallbackCopy(text));
  }
  return Promise.resolve(fallbackCopy(text));
}

function fallbackCopy(text) {
  try {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    document.body.removeChild(ta);
  } catch (e) { /* ignore */ }
}

let toastTimer = null;
function showToast(text) {
  let toast = document.getElementById('toast');
  if (!toast) {
    toast = document.createElement('div');
    toast.id = 'toast';
    toast.className = 'toast';
    document.body.appendChild(toast);
  }
  toast.textContent = text;
  toast.classList.add('toast--show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove('toast--show'), 4000);
}

const viberLink = document.getElementById('viber-link');
if (viberLink) {
  viberLink.addEventListener('click', () => {
    if (!currentOrderText) return;
    const t = I18N[currentLang] || I18N[DEFAULT_LANG];
    copyToClipboard(currentOrderText);
    showToast(t.order_copied);
  });
}

// ===== LANGUAGE SWITCHER =====
(function initLang() {
  let saved = DEFAULT_LANG;
  try { saved = localStorage.getItem('lang') || DEFAULT_LANG; } catch (e) { /* ignore */ }
  if (!I18N[saved]) saved = DEFAULT_LANG;

  const select = document.getElementById('lang-select');
  if (select) {
    select.value = saved;
    select.addEventListener('change', e => applyLang(e.target.value));
  }
  applyLang(saved);
})();

// ===== SMOOTH SCROLL for older browsers =====
document.querySelectorAll('a[href^="#"]').forEach(a => {
  a.addEventListener('click', e => {
    const href = a.getAttribute('href');
    if (href === '#') {
      e.preventDefault();
      window.scrollTo({ top: 0, behavior: 'smooth' });
      return;
    }
    const target = document.querySelector(href);
    if (target) {
      e.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  });
});

